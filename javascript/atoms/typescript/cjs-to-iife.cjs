// Converts a CommonJS-compiled TypeScript atom into a browser-injectable IIFE.
//
// TypeScript --module commonjs emits a header consisting of:
//   "use strict";
//   Object.defineProperty(exports, "__esModule", { value: true });
// and a footer of the form:
//   exports.default = <functionName>;
//
// This script strips those module-system lines, then wraps the remaining body
// in an IIFE that returns the exported default function, producing the same
// browser-injectable format previously generated by --module none.

const fs = require('node:fs')

const [inputPath, outputPath] = process.argv.slice(2)

if (!inputPath || !outputPath) {
  throw new Error('Expected input and output file paths')
}

const input = fs.readFileSync(inputPath, 'utf8')
const lines = input.split('\n')

// Strip known CJS boilerplate lines.
const stripped = lines.filter(line => {
  if (line.trim() === '"use strict";') return false
  if (line.startsWith('Object.defineProperty(exports, "__esModule"')) return false
  return true
})

// Find and remove the `exports.default = <name>;` line, capturing the name.
let exportedName = null
const body = stripped.filter(line => {
  const match = line.match(/^exports\.default\s*=\s*(\w+)\s*;?\s*$/)
  if (match) {
    exportedName = match[1]
    return false
  }
  return true
})

if (!exportedName) {
  throw new Error(
    `Could not find 'exports.default = <name>' in: ${inputPath}\n` +
    `Last 3 lines:\n${lines.slice(-3).join('\n')}`
  )
}

// Remove leading/trailing blank lines from the body so the IIFE is compact.
while (body.length && body[0].trim() === '') body.shift()
while (body.length && body[body.length - 1].trim() === '') body.pop()

const output = `(function () {\n${body.join('\n')}\n  return ${exportedName};\n})()`
fs.writeFileSync(outputPath, output)
